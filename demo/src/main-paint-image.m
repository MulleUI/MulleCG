#define _GNU_SOURCE

#import "import-private.h"



#include "bitmap2.inc"



static BOOL   drawStuff( CGGraphicsLayer *layer, CGContext *context)
{
   CGRect            canvas;
   CACircle          circle;
   CGFloat           strokeWidth;
   NSInteger         index;
   CGStrokeOptions   options;
   CGImage           *image;

   image = [CGImage imageWithRGBABytes:bitmap2
                            bitmapSize:CGPixelSizeMake( 32, 32)
                          textureFlags:CGImageFlagRepeatX|CGImageFlagRepeatY
                               context:context];

   canvas        = [layer canvas];
   circle        = CGRectGetInnerCircle( canvas);
   circle.radius = circle.radius - 16.0;
   index         = 30 - [context numberOfFrames] % 60;
   strokeWidth   = (index < 0 ? -index : index) + 2;

   if( ([context numberOfFrames] / 120) & 0x1)
   {
      //
      // this will use "circle" size to derive a fill from image
      // as the image is only 32x32 the texture will be "zoomed"
      //
      CGContextStrokeCircleWithPaintable( context, circle, strokeWidth, image);
   }
   else
   {
      //
      // here we use image size to fill, since the desired size is the
      // image size and we used repeat, we get the repeating pattern...
      //
      CGContextBeginPath( context);
      CGContextCircle( context, circle);
      CGContextStrokeWidth( context, strokeWidth);
      options = CGStrokeOptionsDefault;
      CGContextStrokePaintableOptions( context,
                                           image,
                                           CGRectMakeWithSize( [image size]),
                                           strokeWidth,
                                           &options);
      CGContextStroke( context);
   }
   return( YES);
}



int   main( int argc, char *argv[])
{
   UIApplication   *app;
   UIWindow        *window;

   app = [UIApplication sharedInstance];

   window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 150, 150)];
   [window setDrawCallback:(CGGraphicsLayerDrawCallback_t *) drawStuff];
   [window setBackgroundColor:CGColorMakeWhite()];
   [window setFrameRateHz:30.0];
   [app addWindow:window];

   return( [app runApp]);
}


