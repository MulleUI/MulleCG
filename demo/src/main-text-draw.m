#define _GNU_SOURCE

#import "import-private.h"

#include <string.h>


static void   drawStuff( CALayer *layer, CGContext *context)
{
   struct NVGcontext  *vg;
   CGFont             *font;
   CGRect             canvas;
   CGRect             rect;

   vg     = CGContextGetNVGContext( context);
   font   = [context fontWithNameUTF8String:"sans"];
   canvas = [layer canvas];
   rect   = CGSizeCenterInRect( CGSizeMake( 300, 100), canvas);

   mvgStrokeRectWithColor( vg, rect, 1.0, CGColorMakeGray());
   mvgStrokeLineH( vg, CGRectGetMinX( rect), CGRectGetMaxX( rect), CGRectGetMidY( rect), CGColorMakeGray());
   mvgFontSize( vg, 80.0);
   mvgTextColor( vg, CGColorMakeGreen(), CGColorMakeWhite());
   mvgExtendedAlignedText( vg,
                          " uo xu", // Vya Con",
                          NULL,
                          CGPointMake( CGRectGetMinX( rect),
                          CGRectGetMaxY( rect)),
                          NVG_ALIGN_RIGHT|NVG_ALIGN_BOTTOM,
                          MVGTextAlignVisually);
}


void   setupScene( UIWindow *window)
{
   UIView   *view;
   CGRect   frame;

   frame = [[window contentPlane] contentRect];

   view  = [UIView viewWithFrame:frame];
   [view setAutoresizingMask:UIViewAutoresizingFlexibleWidth|UIViewAutoresizingFlexibleHeight];
   [view setDrawCallback:(CALayerDrawCallback_t *) drawStuff];
   [[window contentPlane] addSubview:view];
}


int   main( int argc, char *argv[])
{
   UIApplication   *app;
   UIWindow        *window;
   NSUInteger      styleMask;

   app = [UIApplication sharedInstance];

   @autoreleasepool
   {
      styleMask = UIWindowStyleMaskDefault;
      styleMask = UIWindowsStyleMaskBySetting( styleMask, UIWindowStyleResizable, YES);
      styleMask = UIWindowsStyleMaskBySetting( styleMask, UIWindowStyleRetained, NO);

      window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 1000, 600)
                         titleUTF8String:"Demo"
                               styleMask:styleMask];
      assert( window);
      [window setBackgroundColor:CGColorMakeWhite()];
      setupScene( window);

      [app addWindow:window];
   }
   return( [app run]);
}


