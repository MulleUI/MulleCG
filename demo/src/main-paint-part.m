#define s_bengal_jpg  (sizeof( bengal_jpg) - 1)

static UIImage  *AppTigerImage;



static BOOL   drawStuff( CGGraphicsLayer *layer, CGContext *context)
{
   CGRect   canvas;
   CGRect   rect;
   CGRect   imageRect;

   canvas    = [layer canvas];
   imageRect = CGRectMakeWithSize( [AppTigerImage size]);

   // draw full tiger with 0.1 alpha as backdrop
   CGContextSave( context);
   {
      CGContextBeginPath( context);
      CGContextRect( context, canvas);
      CGContextGlobalAlpha( context, 0.1);
      CGContextFillPaintableOptions( context, AppTigerImage, imageRect, NULL);
      CGContextFill( context);   
   }
   CGContextRestore( context);

   // draw various parts of the tiger image with full alpha
   CGContextBeginPath( context);
   CGContextRect( context, CGRectMake( 200, 100, 100, 100));
   CGContextFillPaintableOptions( context, AppTigerImage, imageRect, NULL);
   CGContextFill( context);   

   CGContextBeginPath( context);
   CGContextRect( context, CGRectMake( 450, 300, 400, 100));
   CGContextFillPaintableOptions( context, AppTigerImage, imageRect, NULL);
   CGContextFill( context);   

   CGContextBeginPath( context);
   CGContextCircle( context, CACircleMake( 325, 350, 75));
   CGContextFillPaintableOptions( context, AppTigerImage, imageRect, NULL);
   CGContextFill( context);   

   return( YES);
}


int   main( int argc, char *argv[])
{
   UIApplication   *app;
   UIWindow        *window;
   CGSize          imageSize;

   app = [UIApplication sharedInstance];

   AppTigerImage = [[UIImage imageWithFileCData:mulle_data_make( bengal_jpg, s_bengal_jpg)
                                                   allocator:NULL] retain];
   imageSize = [AppTigerImage size];
   if( CGSizeGetArea( imageSize) < 32)
      return( 1);

   window = [UIWindow windowWithFrame:CGRectMake( 0, 0, imageSize.width * 2.0 / 3.0, imageSize.height * 2.0 / 3.0)];
   [window setDrawCallback:(CGGraphicsLayerDrawCallback_t *) drawStuff];
   [window setBackgroundColor:CGColorMakeWhite()];

   [app addWindow:window];

   return( [app runApp]);
}


