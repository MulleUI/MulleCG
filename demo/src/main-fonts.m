#define _GNU_SOURCE

#import "import-private.h"

#define TEXT         "Der VfL Bochum hat den zweiten Sieg in Folge gefeiert."
#define EMOJI_TEXT   "🎩🦁🃏👀🎩"

// https://fontello.github.io/entypo/demo.html
#define ICONS_TEXT   "➕➖"


static void   drawStuff( CALayer *layer, CGContext *context)
{
   CGRect               rect;
   struct NVGcontext    *vg;
   CGFont               *font;

   font = [context fontWithNameUTF8String:"sans"];
   font = [context fontWithNameUTF8String:"sans-bold"];
   font = [context fontWithNameUTF8String:"icons"];
   rect = [layer canvas];

   vg = CGContextGetNVGContext( context);

   nvgFontFace( vg, "sans");
   nvgTextAlign( vg, NVG_ALIGN_LEFT | NVG_ALIGN_BASELINE);
   nvgTextColor( vg, nvgRGBA( 0, 0, 0, 0xFF), nvgRGBA( 0xFF, 0xFF, 0xFF, 0xFF)); // TODO: use textColor

   nvgFontSize( vg, 20.0);
   nvgText( vg, rect.origin.x,
                rect.origin.y + 20.0,
                TEXT,
                NULL);

   nvgFontFace( vg, "sans-bold");
   nvgText( vg, rect.origin.x,
                rect.origin.y + 50.0,
                TEXT,
                NULL);

   // TODO: emojis aren't colorized
   nvgFontFace( vg, "sans");
   nvgText( vg, rect.origin.x,
                rect.origin.y + 80.0,
                EMOJI_TEXT,
                NULL);

   // TODO: emojis aren't bold
   nvgFontFace( vg, "sans-bold");
   nvgText( vg, rect.origin.x,
                rect.origin.y + 120.0,
                EMOJI_TEXT,
                NULL);

   // TODO: why so small ?
   nvgFontFace( vg, "icons");
   nvgFontSize( vg, 40.0);
   nvgText( vg, rect.origin.x,
                rect.origin.y + 150.0,
                ICONS_TEXT,
                NULL);   
}


void   setupScene( UIWindow *window)
{
   UIView        *view;
   CGRect         frame;
   UIEdgeInsets   insets;

   frame  = [[window contentPlane] contentRect];

   insets = UIEdgeInsetsMake( 30, 30, 30, 30);
   frame  = UIEdgeInsetsInsetRect( frame, insets);

   view  = [UIView viewWithFrame:frame];
   [view setMargins:insets];
   [view setAutoresizingMask:UIViewAutoresizingFlexibleWidth|UIViewAutoresizingFlexibleHeight];
   [view setDrawCallback:(CALayerDrawCallback_t *) drawStuff];
   [[window contentPlane] addSubview:view];
}


int   main( int argc, char *argv[])
{
   UIApplication   *app;
   UIWindow        *window;
   NSUInteger      styleMask;

   app = [UIApplication sharedInstance];

   @autoreleasepool
   {
      styleMask = UIWindowStyleMaskDefault;
      styleMask = UIWindowsStyleMaskBySetting( styleMask, UIWindowStyleResizable, YES);
      styleMask = UIWindowsStyleMaskBySetting( styleMask, UIWindowStyleRetained, NO);

      window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 800, 600)
                         titleUTF8String:"Demo"
                               styleMask:styleMask];

      assert( window);
      [window setBackgroundColor:CGColorMakeWithRGBA( 1.0, 1.0, 1.0, 1.0)];
      setupScene( window);

      [app addWindow:window];
   }
   return( [app run]);
}


