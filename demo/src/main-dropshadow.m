#define _GNU_SOURCE

#import "import-private.h"


#define ROWS  2
#define COLS  2
#define WEIGH( x)   ((double) (x) / (COLS * ROWS - 1))

#define DISTANCE   80


static BOOL   drawStuff( CALayer *layer, CGContext *context)
{
   CGRect               canvas;
   CGRect               rect;
   NSUInteger           x, y;
   NSUInteger           i;
   CGRect               rects[ ROWS * COLS];
   CGFloat              cornerRadius;
   struct CGShadow   shadow;
   NSUInteger           frameNr;
   struct NVGcontext    *vg;

   canvas = [layer canvas];
   rect   = CGRectInset( canvas, DISTANCE, DISTANCE);

   CGRectPartitionIntoRowsAndColumns( rect,
                                      CGSizeMake( DISTANCE, DISTANCE),
                                      ROWS,
                                      COLS,
                                      rects);

   frameNr      = [context numberOfFrames];
   vg           = CGContextGetNVGContext( context);
   i = 0;
   for( y = 0; y < ROWS; y++)
      for( x = 0; x < COLS; x++)
      {
         shadow          = CGShadowMake( CGPointZero, (x + y * COLS) * 8.0, CGColorMakeGray());
         shadow.hole     = (frameNr & 0x2) ? 1 : 0;
         rect            = CGRectIntegral( rects[ i]);
         if( (frameNr & 0x4))
            rect = CGRectContract( rect, rect.size.height / 4.0, 0xFF);
         cornerRadius    = rect.size.width / 16.0;
         mvgFillRoundedShadow( vg, rect, cornerRadius, &shadow);

         if( frameNr & 0x1)
         {
            mvgStrokeRoundedRectWithColor( vg, CGRectExtrude( rect, shadow.blur, shadow.blur), cornerRadius, 1.0f, CGColorMakeRed());
            mvgStrokeRoundedRectWithColor( vg, rect, cornerRadius, 1.0f, CGColorMakeOrange());
//            mvgStrokeRoundedRectWithColor( vg, CGRectInset( rect, shadow.blur, shadow.blur), cornerRadius, CGColorMakeYellow());
         }
         ++i;
      }

   return( YES);
}



int   main( int argc, char *argv[])
{
   UIApplication   *app;
   UIWindow        *window;

   app = [UIApplication sharedInstance];

   window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 800, 600)];
   [window setDrawCallback:(CALayerDrawCallback_t *) drawStuff];
   [window setBackgroundColor:CGColorMakeWithRGBA( 1.0, 1.0, 1.0, 1.0)];
   [window setFrameRateHz:0.5];
   return( [app runWindow:window]);
}


