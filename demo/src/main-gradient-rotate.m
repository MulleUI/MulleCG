#define _GNU_SOURCE

#import "import-private.h"

#include <string.h>
#include <time.h>


static BOOL   drawStuff( CALayer *layer, CGContext *context)
{
   CGRect              canvas;
   CGRect              rect;
   CGRect              rects[ 3][ 3];
   CGGradient          *gradient;
   struct NVGcontext   *vg;
   unsigned int        i, j;
   CAAngle             angle;
   NVGpaint            paint;
   char                buf[ 128];

   // directions as we want the texture rotated in each rectangle
   static CAAngle   directions[ 9] =
   {
      CAAngleNW,
      CAAngleN,
      CAAngleNE,

      CAAngleW,
      NAN,
      CAAngleE,

      CAAngleSW,
      CAAngleS,
      CAAngleSE
   };


   canvas = [layer canvas];
   vg     = CGContextGetNVGContext( context);

   nvgBeginPath( vg);
   {
      mvgRect( vg, canvas);
      mvgStrokeWidth( vg, 8);
      mvgStrokeColor( vg, CGColorMakeWithHexColor( 0x8020A0FF));
   }
   nvgStroke( vg);

   CGRectPartition3x3( CGRectInset( canvas, 4, 4), CGSizeMake( 4, 4), rects);

   for( j = 0; j < 3; j++)
   {
      for( i = 0; i < 3; i++)
      {
         angle = directions[ i + j * 3];
         if( isnan( angle))
            continue;
         MulleUICLog( "angle #%d: %g (%g°)", i + j * 3, angle, CAAngleToDegrees( angle));

         rect = CGRectIntegral( rects[ j][ i]);

         mvgBeginPath( vg);
         mvgRect( vg, rect);

         // TODO: still a little weird
         // the "unrotated" gradient will be 0.0 rotation, which is North
         // but we want it so show up in East, so rotate it.
         angle    = CAAngleRotate( angle, CARotation90);
         gradient = [CGGradient gradientWithStartColor:CGColorMakeGoldenrod()
                                              endColor:CGColorMakeMagenta()
                                              rotation:CAAngleToRotation( angle)];
         paint    = [gradient linearGradientNVGpaintWithBounds:rect
                                                    NVGcontext:vg];
         mvgFillPaint( vg, paint);
         mvgFill( vg);

         [context useFontWithNameUTF8String:"sans"];
         mvgFontSize( vg, 12);
         mvgTextColor( vg, CGColorMakeBlack(), CGColorMakeOrange());
         sprintf( buf, "%.1f°", CAAngleToDegrees( angle));
         mvgTextInRect( vg, buf, NULL, rect, CGContentModeLeft, MVGTextAlignVisually);
      }
   }
   return( YES);
}


void   setupScene( UIWindow *window)
{
   UIView   *view;
   CGRect   frame;

   frame  = [[window contentPlane] contentRect];
   view   = [UIView viewWithFrame:frame];
   [view setDrawCallback:(CALayerDrawCallback_t *) drawStuff];
   [[window contentPlane] addSubview:view];
}


int   main( int argc, char *argv[])
{
   UIWindow         *window;
   UIApplication    *app;

   app = [UIApplication sharedInstance];
   @autoreleasepool
   {
      window = [[[UIWindow alloc] initWithFrame:CGRectMake( 0.0, 0.0, 600, 400)
                                titleUTF8String:"Demo"
                                      styleMask:UIWindowStyleMaskDefault & ~UIWindowStyleRetained] autorelease];

      assert( window);
      [window setBackgroundColor:CGColorMakeWithRGBA( 0.5, 0.5, 0.5, 1.0)];
      setupScene( window);
      [app addWindow:window];
   }
   return( [app run]);
}




