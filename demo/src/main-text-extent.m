#define _GNU_SOURCE

#import "import-private.h"

#include <stdio.h>
static BOOL   drawStuff( CGGraphicsLayer *layer, CGContext *_context)
{
   CGContext           *context = _context;
   CGTextBoundsInfo    info;
   CGFont              *font;
   font = [context fontWithNameUTF8String:"sans"];
   assert( font);

   CGContextFontFace( context, "sans");
   CGContextFontSize( context, 12.0);

   info = CGContextTextBoundsInfo( context, CGPointZero, "abc", -1);
   mulle_fprintf( stderr, "abc: %s\n", CGRectUTF8String( info.bounds));

   // has space in back
   info = CGContextTextBoundsInfo( context, CGPointZero, "abc ", -1);
   mulle_fprintf( stderr, "abc : %s\n", CGRectUTF8String( info.bounds));
   fprintf( stderr, "App exits intentionally now\n");
   exit( 0);
   return( NO);
}


int   main( int argc, char *argv[])
{
   UIWindow        *window;
   UIApplication   *app;

   app = [UIApplication sharedInstance];
   window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 200, 200)
                      titleUTF8String:"Demo"
                            styleMask:UIWindowStyleMaskDefault];
   assert( window);

   [window setDrawCallback:drawStuff];
   return( [app runWindow:window]);
}

