#define _GNU_SOURCE

#import "import-private.h"

#include <stdio.h>


static void   drawStuff( CALayer *layer, CGContext *context)
{
   struct NVGcontext   *vg;
   CGRect              canvas;
   float               bounds[ 4];
   CGFont              *font;

   vg = CGContextGetNVGContext( context);

   font = [context fontWithNameUTF8String:"sans"];
   assert( font);

   nvgFontFace( vg, "sans");
   nvgFontSize( vg, 12.0);

   nvgTextBounds( vg, 0, 0, "abc", NULL, bounds);
   fprintf( stderr, "abc: %.1f %.1f %.1f %1f\n",
                    bounds[ 0],
                    bounds[ 1],
                    bounds[ 2],
                    bounds[ 3]);

   // has space in back
   nvgTextBounds( vg, 0, 0, "abc ", NULL, bounds);
   fprintf( stderr, "abc : %.1f %.1f %.1f %1f\n",
                    bounds[ 0],
                    bounds[ 1],
                    bounds[ 2],
                    bounds[ 3]);
   fprintf( stderr, "App exits intentionally now\n");
   exit( 0);
}


int   main( int argc, char *argv[])
{
   UIWindow   *window;

   window = [UIWindow windowWithFrame:CGRectMake( 0.0, 0.0, 200, 200)
                      titleUTF8String:"Demo"
                            styleMask:UIWindowStyleMaskDefault];
   assert( window);

   [window setDrawCallback:drawStuff];
   return( UIApplicationRunWindow( window));
}



