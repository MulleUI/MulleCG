static BOOL   drawStuff( CGGraphicsLayer *layer, CGContext *context)
{
   CGRect       canvas;
//   NSUInteger   glyph;

   canvas = [layer canvas];

   CGContextFontSize( context, 32.0); // Converted from nvgFontSize
   CGContextSave( context); // Converted from nvgSave
   {
      CGContextStrokeLineHWithColor( context, CGPointMake( 0, CGRectGetMidY( canvas)),
                                              CGRectGetWidth( canvas),
                                              1.0,
                                              CGColorMakeGray());
      CGContextStrokeLineVWithColor( context, CGPointMake( CGRectGetMidX( canvas), 0),
                                              CGRectGetHeight( canvas),
                                              1.0,
                                              CGColorMakeGray());

      CGContextTranslate( context, CGRectGetCenterPoint( canvas));

      CGContextTextBackgroundColor( context, CGColorMakeWhite());
      CGContextTextColor( context, CGColorMakeBlack());

      CGContextTextAlignment( context, UITextAlignmentLeft);
      CGContextText( context, CGPointMake( 0, -32), "Left", -1);

      CGContextTextAlignment( context, UITextAlignmentCenter);
      CGContextText( context, CGPointMake( 0, 0), "Center", -1);

      CGContextTextAlignment( context, UITextAlignmentRight);
      CGContextText( context, CGPointMake( 0, 32), "Right", -1);
   }
   CGContextRestore( context);

//   glyph = [layer glyph];
//   if( glyph)
//   {
//      CGContextFontSize( context, 12.0); // Converted from nvgFontSize
//      CGContextTextBackgroundColor( context, CGColorMakeWhite());
//      CGContextTextColor( context, CGColorMakeBlack());
//      CGContextCombinedTextAlignment( context, CGTextAlignLeft | CGTextAlignTop);
//
//      CGContextFormat( context, CGPointMake( 1, 1), "glyph: '%c'", (int) glyph);
//   }

   return( YES);
}


