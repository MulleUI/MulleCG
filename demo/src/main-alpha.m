#define _GNU_SOURCE

#import "import-private.h"

#include <string.h>
#include <time.h>


#define ROWS             10
#define COLUMNS          10
#define STEPS            10 // Number of rectangles to draw in each direction
#define ALPHA_FACTOR    1.5

static BOOL   drawStuff( CGGraphicsLayer *layer, CGContext *context)
{
   CGRect              canvas;
   CGRect              rects[ ROWS][ COLUMNS];
   NSUInteger          i, j;
   CGRect              cellRect;
   CGFloat             alpha;
   CGColor             color;

   canvas = [layer canvas];

   // Draw a black background
   CGContextFillRectWithColor( context, canvas, CGColorMakeBlack());

   // Set standard alpha blending mode (Source Over)
   // This is the default, but explicitly setting it for clarity
   CGContextGlobalCompositeOperation( context, CGCompositeOperationLighter);

   // Divide the canvas into a grid
   CGRectPartitionIntoRowsAndColumns( CGRectInset( canvas, 1, 1), CGSizeMake( 1, 1), ROWS, COLUMNS, (CGRect *) rects);

   // Loop through the grid and draw alpha gradients in four directions
   for( i = 0; i < ROWS; i++)
   {
      for( j = 0; j < COLUMNS; j++)
      {
         cellRect = rects[ i][ j];

         // alpha for color0 is left-right
         alpha = (float) j / COLUMNS;
         color = CGColorMakeWithHSLA( 0.25, 1.0, 0.5, alpha / ALPHA_FACTOR);
         CGContextFillRectWithColor( context, cellRect, color);

         // alpha for color1 is right-left
         alpha = 1.0 - alpha;
         color = CGColorMakeWithHSLA( 0.75, 1.0, 0.5, alpha / ALPHA_FACTOR);
         CGContextFillRectWithColor( context, cellRect, color);

         // alpha for color2 is top-bottom
         alpha = (float) i / ROWS;
         color = CGColorMakeWithHSLA( 0.0, 1.0, 0.5, alpha / ALPHA_FACTOR);
         CGContextFillRectWithColor( context, cellRect, color);

         // alpha for color3 is bottom-top
         alpha = 1.0 - alpha;
         color = CGColorMakeWithHSLA( 0.50, 1.0, 0.5, alpha / ALPHA_FACTOR);
         CGContextFillRectWithColor( context, cellRect, color);
      }
   }

   return( YES);
}



int   main( int argc, char *argv[])
{
   UIWindow         *window;
   UIApplication    *app;

   app = [UIApplication sharedInstance];
   @autoreleasepool
   {
      window = [[[UIWindow alloc] initWithFrame:CGRectMake( 0.0, 0.0, 600, 600)
                                titleUTF8String:"Alpha Gradient Demo"
                                      styleMask:UIWindowStyleMaskDefault & ~UIWindowStyleRetained] autorelease];

      assert( window);
      [window setBackgroundColor:CGColorMakeWithRGBA( 0.5, 0.5, 0.5, 1.0)];
      [[window contentView] setDrawCallback:(CGGraphicsLayerDrawCallback_t *) drawStuff];
      [app addWindow:window];
   }
   return( [app runApp]);
}


