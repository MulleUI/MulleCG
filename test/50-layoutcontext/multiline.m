#define _GNU_SOURCE

#import <MulleCG/MulleCG.h>


int   main( int argc, char *argv[])
{
   CGLayoutContext          *context;
   CGRect                   bounds;
   CGRect                   vbounds;
   struct UITextMetrics     metrics;
   struct UIGlyphPosition   positions[ 64];
   struct UITextRow         rows[ 8];
   NSUInteger               i, n;
   char                     *text;
   CGFloat                  breakRowWidth;
   NSLineBreakMode          mode;

   @autoreleasepool
   {
      context = [CGLayoutContext object];

      text    = "VfL Bochum 1848\nvs.\nWerder Bremen";
      [context useDefaultFont];
      [context setFontSize:16.0f];
      [context setTextAlign:NVG_ALIGN_MIDDLE];

      // can't do anything else than NSLineBreakByWordWrapping currently
      for( mode = NSLineBreakByWordWrapping; mode <= NSLineBreakByWordWrapping; mode++)
      {
         [context setLineBreakMode:mode];

         for( breakRowWidth = 50.0; breakRowWidth <= 150.0; breakRowWidth += 50.0)
         {
            printf( "%s breakRowWidth: %g:\n", NSLineBreakModeUTF8String( mode), breakRowWidth);
            n = [context getTextRows:rows
                               count:sizeof( rows) / sizeof( rows[ 0])
                                text:text
                              length:(NSUInteger) -1
                       breakRowWidth:breakRowWidth];

            bounds = [context getTextRowBounds:rows
                                         count:n];

            printf( "\t%tu: %s\n", n, CGRectUTF8String( bounds));
            for( i = 0; i < n; i++)
            {
               printf( "\t\t\"%.*s\" w=%g minx=%g maxx=%g\n",
                           (int) (rows[ i].end - rows[ i].start), rows[ i].start,
                           rows[ i].width,
                           rows[ i].minx,
                           rows[ i].maxx);
            }
            printf( "\n");
         }
      }
   }
   return( 0);
}


